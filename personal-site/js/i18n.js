(function () {
  "use strict";
  var dict = window.I18N;

  function getLang() {
    var stored = null;
    try { stored = localStorage.getItem("lang"); } catch (e) {}
    if (stored === "zh" || stored === "en") return stored;
    var nav = (navigator.language || "en").toLowerCase();
    return nav.indexOf("zh") === 0 ? "zh" : "en";
  }

  function applyLang(lang) {
    var set = dict[lang] || dict.en;
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

    var nodes = document.querySelectorAll("[data-i18n]");
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      var val = set[el.getAttribute("data-i18n")];
      if (val === undefined) continue;
      if (el.tagName === "META") {
        el.setAttribute("content", val);
      } else if (el.tagName === "TITLE") {
        el.textContent = val;
      } else {
        el.innerHTML = val;
      }
    }

    var btn = document.getElementById("lang-toggle");
    if (btn) {
      btn.textContent = lang === "en" ? "中文" : "EN";
      btn.setAttribute("aria-label", lang === "en" ? "切换到中文" : "Switch to English");
    }

    var themeBtn = document.getElementById("theme-toggle");
    if (themeBtn) {
      themeBtn.setAttribute("aria-label", lang === "zh" ? "切换浅色 / 深色主题" : "Toggle light / dark theme");
    }
  }

  var lang = getLang();
  applyLang(lang);

  // Delegated click so it works even if the button is re-rendered.
  document.addEventListener("click", function (e) {
    var btn = e.target && e.target.closest ? e.target.closest("#lang-toggle") : null;
    if (!btn) return;
    lang = lang === "en" ? "zh" : "en";
    try { localStorage.setItem("lang", lang); } catch (err) {}
    applyLang(lang);
  });
})();
